def wrap(caption, label, colspec, header, rows, note=None, align="r"):
    lines = [
        "% Generated by scripts/emit_latex_tables.py -- do not edit by hand.",
        "\\begin{table}[htbp]",
        "  \\centering",
        "  \\caption{%s}" % caption,
        "  \\label{%s}" % label,
        "  \\begin{tabular}{%s}" % colspec,
        "    \\toprule",
        "    " + " & ".join(header) + " \\\\",
        "    \\midrule",
    ]
    for r in rows:
        lines.append("    " + " & ".join(r) + " \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    if note:
        lines.append("  \\par\\smallskip\\footnotesize %s" % note)
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


