"""
Golden-input check reference generator: runs the three quantized NPU
segments (segA/segB/segC .tflite) on a single fixed test image via the
local PC TFLite interpreter, and emits:
  - a C header with the image pre-quantized to INT8 (segA's exact input
    quantization), for firmware to embed and feed as a fixed test vector
  - the expected INT8 output of every intermediate/final tensor, printed as
    plain text for manual/scripted diffing against the board's own
    UART-dumped output values

Test image: GTSRB official test set, 00000.ppm, true label 16
("Vehicles over 3.5 metric tons prohibited" -- a safety-critical
prohibitory class), ROI (6,5,48,49). Picked as a representative real image,
not cherry-picked for any particular outcome.

Usage: python tools/golden/gen_golden.py
"""
from __future__ import annotations

import numpy as np
from PIL import Image
import tensorflow as tf

TARGET_SIZE = 48
INPUT_MEAN = 127.5
INPUT_STD = 127.5
ROI = (6, 5, 48, 49)
TRUE_LABEL = 16

HERE = __file__.rsplit("\\", 1)[0] if "\\" in __file__ else __file__.rsplit("/", 1)[0]


def load_and_normalize(path: str, roi) -> np.ndarray:
    with Image.open(path) as img:
        img = img.convert("RGB")
        if roi is not None:
            img = img.crop(roi)
        img = img.resize((TARGET_SIZE, TARGET_SIZE), Image.BILINEAR)
        arr = np.asarray(img, dtype=np.uint8)
    return (arr.astype(np.float32) - INPUT_MEAN) / INPUT_STD


def quantize(arr: np.ndarray, scale: float, zero_point: int) -> np.ndarray:
    q = np.round(arr / scale + zero_point).clip(-128, 127).astype(np.int8)
    return q


def run_segment(tflite_path: str, input_array: np.ndarray):
    interp = tf.lite.Interpreter(model_path=tflite_path)
    interp.allocate_tensors()
    in_detail = interp.get_input_details()[0]
    interp.set_tensor(in_detail["index"], np.expand_dims(input_array, axis=0))
    interp.invoke()
    outputs = []
    for d in interp.get_output_details():
        t = interp.get_tensor(d["index"])[0]
        outputs.append({"name": d["name"], "shape": list(t.shape), "data": t,
                          "scale": d["quantization"][0], "zero_point": d["quantization"][1],
                          "last_dim": t.shape[-1]})
    return outputs


def find(outputs, last_dim_equals=None, last_dim_not=None):
    for o in outputs:
        if last_dim_equals is not None and o["last_dim"] == last_dim_equals:
            return o
        if last_dim_not is not None and o["last_dim"] != last_dim_not:
            return o
    raise ValueError("no matching output")


def c_array(name: str, arr: np.ndarray) -> str:
    flat = arr.flatten().astype(np.int8)
    values = ", ".join(str(int(v)) for v in flat)
    return f"static const int8_t {name}[{flat.size}] = {{ {values} }};"


def main():
    img_path = HERE + "/test_image.ppm"
    img = load_and_normalize(img_path, ROI)
    print(f"input image stats: min={img.min():.4f} max={img.max():.4f} mean={img.mean():.4f}")

    # segA's own input quantization params (needed to quantize the raw image
    # BEFORE feeding it in -- the interpreter expects INT8, not FP32).
    interp = tf.lite.Interpreter(model_path=HERE + "/../generated/segA_int8.tflite")
    interp.allocate_tensors()
    in_detail = interp.get_input_details()[0]
    in_scale, in_zp = in_detail["quantization"]
    img_q = quantize(img, in_scale, in_zp)

    segA_out = run_segment(HERE + "/../generated/segA_int8.tflite", img_q)

    exit1 = find(segA_out, last_dim_equals=43)
    block3 = find(segA_out, last_dim_not=43)
    print(f"\nsegA: exit1_logits (int8) = {exit1['data'].tolist()}")
    print(f"segA: exit1 argmax = {int(np.argmax(exit1['data']))}")
    print(f"segA: block3_features shape = {block3['shape']}, "
          f"first 10 values = {block3['data'].flatten()[:10].tolist()}")

    segB_out = run_segment(HERE + "/../generated/segB_int8.tflite", block3["data"])
    exit2 = find(segB_out, last_dim_equals=43)
    block6 = find(segB_out, last_dim_not=43)
    print(f"\nsegB: exit2_logits (int8) = {exit2['data'].tolist()}")
    print(f"segB: exit2 argmax = {int(np.argmax(exit2['data']))}")
    print(f"segB: block6_features shape = {block6['shape']}, "
          f"first 10 values = {block6['data'].flatten()[:10].tolist()}")

    segC_out = run_segment(HERE + "/../generated/segC_int8.tflite", block6["data"])
    exit3 = segC_out[0]
    print(f"\nsegC: exit3_logits (int8) = {exit3['data'].tolist()}")
    print(f"segC: exit3 argmax = {int(np.argmax(exit3['data']))}")
    print(f"\ntrue label: {TRUE_LABEL}")

    # C header: fixed test image (INT8) for firmware to embed as its test vector
    with open(HERE + "/golden_input.h", "w") as f:
        f.write("/* Auto-generated by tools/golden/gen_golden.py. Do not edit by hand. */\n")
        f.write("#ifndef _GOLDEN_INPUT_H_\n#define _GOLDEN_INPUT_H_\n\n")
        f.write(f"#define GOLDEN_TRUE_LABEL {TRUE_LABEL}\n\n")
        f.write(c_array("golden_image_int8", img_q) + "\n\n")
        f.write("#endif /* _GOLDEN_INPUT_H_ */\n")
    print(f"\nwrote {HERE}/golden_input.h")

    # Plain-text golden reference for comparison against board output
    with open(HERE + "/golden_reference.txt", "w") as f:
        f.write(f"exit1_logits_int8: {exit1['data'].tolist()}\n")
        f.write(f"exit1_argmax: {int(np.argmax(exit1['data']))}\n")
        f.write(f"block3_features_int8_first10: {block3['data'].flatten()[:10].tolist()}\n")
        f.write(f"exit2_logits_int8: {exit2['data'].tolist()}\n")
        f.write(f"exit2_argmax: {int(np.argmax(exit2['data']))}\n")
        f.write(f"block6_features_int8_first10: {block6['data'].flatten()[:10].tolist()}\n")
        f.write(f"exit3_logits_int8: {exit3['data'].tolist()}\n")
        f.write(f"exit3_argmax: {int(np.argmax(exit3['data']))}\n")
        f.write(f"true_label: {TRUE_LABEL}\n")
    print(f"wrote {HERE}/golden_reference.txt")


if __name__ == "__main__":
    main()
